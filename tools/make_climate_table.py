"""Emit BiomeClimateTable.java for the 1.21.1 port.

The anchoring rules are the ones verified on 26.3 and live in that project's
tools/generate_content.py: the climate bands, the popular erosion and weirdness windows, and the
lane widths. This drives them over the *1.21.1* vanilla climate list, because that is the list the
1.21.1 world actually samples from, and writes the Java table into this project.

The vanilla list is captured from a running server: while the biome source is being built, log every
surface point of the vanilla parameter list and keep the lines it writes as
`VANILLA-CELL <biome> ParameterPoint[...]` (see tools/vanilla_cells.txt).

Run it from the 1.21.1 project: python tools/make_climate_table.py
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_DUMP = os.path.join(HERE, "vanilla_cells.txt")
DEFAULT_GENERATOR = os.path.join(os.path.dirname(ROOT), "tools")
DEFAULT_OUT = os.path.join(
    ROOT, "src", "main", "java", "net", "revskymc", "terrainrefreshed", "worldgen", "BiomeClimateTable.java"
)

MOD = "terrainrefreshed"

HEADER = """package net.revskymc.terrainrefreshed.worldgen;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.biome.Climate;

/** Climate cells owned by the Terrain Refreshed biomes. Generated by tools/make_climate_table.py. */
public final class BiomeClimateTable {
\tpublic record Entry(
\t\tResourceKey<Biome> biome,
\t\tClimate.Parameter temperature,
\t\tClimate.Parameter humidity,
\t\tClimate.Parameter continentalness,
\t\tClimate.Parameter erosion,
\t\tClimate.Parameter weirdness
\t) {}

\tprivate static final Entry[] ENTRIES = {"""

FOOTER = """\t};

\tprivate BiomeClimateTable() {}

\tpublic static Entry[] entries() {
\t\treturn ENTRIES;
\t}
}"""


def fmt(value):
    return "%.10g" % value


AXES = ("temperature", "humidity", "continentalness", "erosion", "weirdness")

# The one measured exception to the shared 26.3 anchoring. On 1.21.1 alpine_meadow's cell is the only
# one the locate sweep could not reach: from spawn the search gave up entirely, and searches started
# inside the nearest frozen regions - snowy_plains, frozen_peaks, jagged_peaks, snowy_slopes - all
# returned it 6.6 to 7.1 km away, while every other cell came in under 5.3 km. Its band sits on the
# -0.35 erosion step, the tail the erosion noise barely reaches, and the frozen, dry, high-weirdness
# corner of the climate space is already fully partitioned between alpine_meadow, windswept_heights
# and highland_bogs, so widening it downwards in erosion would have swallowed those two.
#
# The two axes with room left are the ones widened here: the drier frozen lane below it and the
# weirdness lanes above it. Together they multiply the cell's climate area from 0.0049 to 0.0195 of
# the space (4x, 11 vanilla biomes anchored instead of 9) and still intersect no other Terrain
# Refreshed cell, so the biome keeps its cold, dry, mountain character instead of becoming a
# different one. tools/climate_audit.py has to keep reporting it unshadowed after this.
CELL_OVERRIDE = {
    "alpine_meadow": {"humidity": (-0.35, 0.1), "weirdness": (0.4, 0.9333)},
}


def apply_overrides(biomes):
    """Replace the bands a version's own terrain makes unreachable."""
    for biome in biomes:
        for axis, band in CELL_OVERRIDE.get(biome["id"], {}).items():
            index = AXES.index(axis)
            low, high = (round(value * 10000) for value in band)

            if tuple(biome["cell"][index]) != (low, high):
                print(
                    "  override %-18s %s [%s, %s] -> [%s, %s]"
                    % (biome["id"], axis, biome["cell"][index][0], biome["cell"][index][1], low, high)
                )
                cell = list(biome["cell"])
                cell[index] = (low, high)
                biome["cell"] = cell


def write_table(path, biomes):
    lines = [HEADER]

    for biome in biomes:
        spans = [
            "\t\t\tClimate.Parameter.span(%sF, %sF)" % (fmt(low / 10000.0), fmt(high / 10000.0))
            for low, high in biome["cell"]
        ]

        lines.append("\t\tnew Entry(")
        lines.append(
            "\t\t\tResourceKey.create(Registries.BIOME, ResourceLocation.fromNamespaceAndPath(\"%s\", \"%s\")),"
            % (MOD, biome["id"])
        )

        for index, span in enumerate(spans):
            lines.append(span + ("," if index + 1 < len(spans) else ""))

        lines.append("\t\t),")

    lines.append(FOOTER)

    os.makedirs(os.path.dirname(path), exist_ok=True)

    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dump", default=DEFAULT_DUMP, help="captured 1.21.1 vanilla climate list")
    parser.add_argument("--generator", default=DEFAULT_GENERATOR, help="directory holding generate_content.py")
    parser.add_argument("--out", default=DEFAULT_OUT, help="BiomeClimateTable.java to write")
    args = parser.parse_args()

    sys.path.insert(0, args.generator)
    import generate_content as authored

    if not os.path.isfile(args.dump):
        raise SystemExit("no captured climate list at %s" % args.dump)

    authored.VANILLA_DUMP = args.dump
    shelves = authored.read_shelves()
    report = authored.allocate_cells(authored.BIOMES, shelves)

    print("version specific anchors:")
    apply_overrides(authored.BIOMES)

    write_table(args.out, authored.BIOMES)

    print("%s: %d vanilla neighbourhoods, %d cells anchored" % (args.dump, len(shelves), len(report)))

    for biome_id, ranges, weirdness in report[:5]:
        print("  %s <- %s weirdness [%s, %s]" % (biome_id, ranges[2], weirdness[0] / 10000.0, weirdness[1] / 10000.0))

    print("wrote %s" % args.out)

    return 0


if __name__ == "__main__":
    sys.exit(main())
